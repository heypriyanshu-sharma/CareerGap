-- STATUS: PROPOSAL ONLY. Apply manually in Supabase dashboard.

create table if not exists public.interview_sessions (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users (id) on delete cascade,
    mode text not null check (mode in ('quick', 'full')),
    target_role text check (char_length(target_role) <= 120),
    resume_id uuid references public.resumes (id) on delete set null,
    questions jsonb not null default '[]'::jsonb,
    answers jsonb,
    feedback jsonb,
    score numeric(5,2),
    weak_areas text[],
    recommendations jsonb,
    status text not null default 'pending' check (status in ('pending', 'completed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    completed_at timestamptz,
    constraint interview_questions_is_array check (jsonb_typeof(questions) = 'array'),
    constraint interview_answers_is_array check (answers is null or jsonb_typeof(answers) = 'array'),
    constraint interview_questions_max check (jsonb_array_length(questions) <= 20),
    constraint interview_answers_max check (answers is null or jsonb_array_length(answers) <= 20)
);

comment on table public.interview_sessions is
    'Interview practice sessions. questions generated by AI; answers+feedback stored after evaluation.';

-- Timestamp trigger
create or replace function public.set_interview_updated_at()
returns trigger language plpgsql security invoker set search_path = public as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists interview_set_updated_at on public.interview_sessions;
create trigger interview_set_updated_at
    before update on public.interview_sessions
    for each row execute function public.set_interview_updated_at();

-- RLS
alter table public.interview_sessions enable row level security;

drop policy if exists "interview_select_own" on public.interview_sessions;
drop policy if exists "interview_insert_own" on public.interview_sessions;
drop policy if exists "interview_update_own" on public.interview_sessions;
drop policy if exists "interview_delete_own" on public.interview_sessions;

create policy "interview_select_own" on public.interview_sessions
    for select to authenticated using ((select auth.uid()) = user_id);
create policy "interview_insert_own" on public.interview_sessions
    for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "interview_delete_own" on public.interview_sessions
    for delete to authenticated using ((select auth.uid()) = user_id);
-- NO UPDATE policy -- direct UPDATE blocked by lack of privilege

grant select, insert, delete on public.interview_sessions to authenticated;

-- Indexes
create index interview_sessions_user_created on public.interview_sessions (user_id, created_at desc);
create index interview_sessions_resume on public.interview_sessions (resume_id) where resume_id is not null;

