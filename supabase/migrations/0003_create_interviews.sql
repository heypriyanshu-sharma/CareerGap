-- Create session (SECURITY INVOKER -- caller has INSERT privilege)
create or replace function public.create_interview_session(
    caller_id uuid,
    p_mode text,
    p_target_role text default null,
    p_resume_id uuid default null,
    p_questions jsonb
)
returns public.interview_sessions
language plpgsql
security invoker
set search_path = public as $$
declare
    v_user_id uuid := (select auth.uid());
    new_session public.interview_sessions;
begin
    if v_user_id is null then
        raise exception 'Unauthenticated.' using errcode = 'P0001';
    end if;
    if v_user_id is distinct from caller_id then
        raise exception 'Not authorized.' using errcode = '42501';
    end if;
    if p_resume_id is not null then
        if not exists (
            select 1 from public.resumes
            where id = p_resume_id and user_id = v_user_id
        ) then
            raise exception 'Resume not found or not owned.' using errcode = 'P0002';
        end if;
    end if;
    insert into public.interview_sessions (user_id, mode, target_role, resume_id, questions, status)
    values (v_user_id, p_mode, p_target_role, p_resume_id, p_questions, 'pending')
    returning * into new_session;
    return new_session;
end; $$;

-- Submit answers (SECURITY DEFINER -- updates protected columns)
create or replace function public.submit_interview_answers(
    caller_id uuid,
    p_session_id uuid,
    p_answers jsonb,
    p_score numeric(5,2),
    p_feedback jsonb,
    p_weak_areas text[],
    p_recommendations jsonb
)
returns public.interview_sessions
language plpgsql
security definer
set search_path = public as $$
declare
    v_user_id uuid := (select auth.uid());
    sess public.interview_sessions;
    q_count int;
    a_count int;
begin
    if v_user_id is null then
        raise exception 'Unauthenticated.' using errcode = 'P0001';
    end if;
    if v_user_id is distinct from caller_id then
        raise exception 'Not authorized.' using errcode = '42501';
    end if;
    select * into sess
    from public.interview_sessions
    where id = p_session_id and user_id = v_user_id
    for update;
    if sess is null then
        raise exception 'Session not found.' using errcode = 'P0002';
    end if;
    if sess.status <> 'pending' then
        raise exception 'Session already completed.' using errcode = 'P0001';
    end if;
    q_count := jsonb_array_length(sess.questions);
    a_count := jsonb_array_length(p_answers);
    if a_count <> q_count then
        raise exception 'Answer count must match question count.' using errcode = 'P0001';
    end if;
    update public.interview_sessions
    set answers = p_answers,
        score = p_score,
        feedback = p_feedback,
        weak_areas = p_weak_areas,
        recommendations = p_recommendations,
        status = 'completed',
        completed_at = now(),
        updated_at = now()
    where id = p_session_id
    returning * into sess;
    return sess;
end; $$;

-- Delete session (SECURITY INVOKER -- caller has DELETE privilege)
create or replace function public.delete_interview_session(
    caller_id uuid,
    p_session_id uuid
)
returns void
language plpgsql
security invoker
set search_path = public as $$
declare
    v_user_id uuid := (select auth.uid());
begin
    if v_user_id is null then
        raise exception 'Unauthenticated.' using errcode = 'P0001';
    end if;
    if v_user_id is distinct from caller_id then
        raise exception 'Not authorized.' using errcode = '42501';
    end if;
    delete from public.interview_sessions
    where id = p_session_id and user_id = v_user_id;
    if not found then
        raise exception 'Session not found.' using errcode = 'P0002';
    end if;
end; $$;

-- Function grants (revoke first for safe re-run)
revoke all on function public.create_interview_session(uuid, text, text, uuid, jsonb) from public;
revoke all on function public.submit_interview_answers(uuid, uuid, jsonb, numeric, jsonb, text[], jsonb) from public;
revoke all on function public.delete_interview_session(uuid, uuid) from public;

grant execute on function public.create_interview_session(uuid, text, text, uuid, jsonb) to authenticated;
grant execute on function public.submit_interview_answers(uuid, uuid, jsonb, numeric, jsonb, text[], jsonb) to authenticated;
grant execute on function public.delete_interview_session(uuid, uuid) to authenticated;